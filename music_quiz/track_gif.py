"""Motion data from a reference GIF -> dance_data.py (positions only; no pixels of the GIF are used in the video).
usage: python3 track_gif.py /path/to/reference.gif"""
import sys
from PIL import Image, ImageSequence
import numpy as np
im = Image.open(sys.argv[1]); fr = [np.array(f.convert("RGB")).astype(int) for f in ImageSequence.Iterator(im)]
H, W = fr[0].shape[:2]; n = len(fr); S = 0.243
gy = np.arange(H)[:, None] * np.ones((1, W)); gx = np.arange(W)[None, :] * np.ones((H, 1))
raw = []
for rgb in fr:
    body = rgb.sum(2) < 735; ys, xs = np.nonzero(body); top = float(ys.min())
    hx = float(np.nonzero(body[int(top):int(top) + 45])[1].mean()); tx = float(np.nonzero(body[130:250])[1].mean()); lx = float(np.nonzero(body[400:490])[1].mean())
    gray = body & (rgb.min(2) > 60) & (rgb.max(2) < 205) & (np.abs(rgb[..., 0] - rgb[..., 2]) < 25)
    low = gray & (gy > top + 62) & (gy < 340)
    def cen(m): return (float(gx[m].mean()), float(gy[m].mean())) if m.sum() > 12 else (np.nan, np.nan)
    nx, ny = cen(low & (gx < tx - 18)); fx, fy = cen(low & (gx > tx + 40))
    raw.append([hx, top, tx, lx, nx, ny, fx, fy])
a = np.array(raw)
for c in range(a.shape[1]):                      # fill gaps, then circular 3-tap smoothing
    col = a[:, c]; bad = np.isnan(col)
    if bad.any(): col[bad] = np.interp(np.nonzero(bad)[0], np.nonzero(~bad)[0], col[~bad], period=n)
    a[:, c] = (np.roll(col, 1) + 2 * col + np.roll(col, -1)) / 4
m = a.mean(0)
rows = []
for r in a:
    rows.append(tuple(float(x) for x in (round(float((r[0] - m[0]) * S), 1), round((r[1] - m[1]) * S, 1), round((r[2] - m[2]) * S, 1), round((r[3] - m[3]) * S, 1),
                 round(50 + (r[4] - m[2]) * S, 1), round(124 - (497 - r[5]) * S, 1), round(50 + (r[6] - m[2]) * S, 1), round(124 - (497 - r[7]) * S, 1))))
with open("dance_data.py", "w") as f:
    f.write("# generated by track_gif.py: per-frame (head_dx, head_dy, torso_dx, legs_dx, nearX, nearY, farX, farY) in sprite px; 44 frames @ 50 ms\n")
    f.write("DANCE_FRAME = 0.05\nDANCE = [\n" + "".join(f"    {r},\n" for r in rows) + "]\n")
print(n, "frames written")
