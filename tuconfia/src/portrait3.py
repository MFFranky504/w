def ramp_skin(sk):
    r, g, b = sk
    return dict(S=sk, s=(int(r * .88), int(g * .74), int(b * .76)), t=(int(r * .72), int(g * .55), int(b * .6)),
                L=(min(255, int(r * 1.03 + 6)), min(255, int(g * 1.04 + 6)), min(255, int(b * 1.04 + 4))))


def stamp(a, items, x0, y0, pal):
    for r, c, txt in items:
        for i, ch in enumerate(txt):
            if ch != '.' and ch in pal: a[y0 + r, x0 + c + i] = (*pal[ch], 255)


def layer(img_arr, col):
    return outline(Image.fromarray(img_arr, 'RGBA'), col).crop((1, 1, W + 1, H + 1))


def portrait3(who='you', expr='n', blink=False, outfit=None):
    CS = resolve(who); style = CS['style']; outfit = outfit or CS['outfit']
    sk = ramp_skin(CS['skin']); hc = CS['hair']; iris = CS['iris']
    pal = {**sk, 'K': (34, 24, 40), 'k': shade(CS['skin'], .58), 'W': (250, 248, 252), 'E': shade(iris, .7),
           'e': tuple(min(255, int(v * 1.7 + 40)) for v in iris), 'P': (20, 14, 28), 'H': (255, 255, 255),
           'M': (150, 62, 74), 'm': (196, 110, 112), 'A': hc['b'], 'a': hc['d'], 'B': hc['l'], 'b': hc['dd']}
    tb, td, tl = TOPS.get(outfit, TOPS['hoodie'])
    out = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    if style == 'tab':                                            # pelo largo por detrás
        bk = Image.new('RGBA', (W, H)); ImageDraw.Draw(bk).polygon(BACK_TAB, fill=(*hc['d'], 255))
        out.alpha_composite(outline(bk, shade(hc['dd'], .6)).crop((1, 1, W + 1, H + 1)))
    # busto pequeño (hombros caídos)
    body = Image.new('RGBA', (W, H)); d = ImageDraw.Draw(body)
    d.polygon([(17, 46), (22, 43), (33, 43), (38, 46), (47, 52), (50, 63), (6, 63), (9, 52)], fill=(*tb, 255))
    d.polygon([(35, 45), (38, 46), (47, 52), (50, 63), (40, 63), (39, 53)], fill=(*td, 255))
    d.polygon([(9, 52), (17, 46), (19, 47), (12, 54), (9, 63), (6, 63)], fill=(*tl, 255))
    if outfit == 'hoodie':
        d.polygon([(17, 46), (21, 42), (34, 42), (38, 46), (33, 49), (22, 49)], fill=(*td, 255))
        d.line([(24, 49), (23, 57)], fill=(246, 246, 252, 255)); d.line([(31, 49), (32, 56)], fill=(246, 246, 252, 255))
    elif outfit == 'grey':
        d.polygon([(21, 44), (34, 44), (32, 47), (23, 47)], fill=(*td, 255))
    elif outfit == 'cardigan':
        d.polygon([(22, 44), (33, 44), (27, 54)], fill=(252, 242, 226, 255)); d.line([(27, 54), (27, 63)], fill=(*td, 255))
    elif outfit == 'plaid':
        for y in range(48, 63, 4): d.line([(8, y), (48, y)], fill=(*td, 255))
        for x in range(10, 48, 5): d.line([(x, 46), (x, 63)], fill=(*td, 255))
        d.polygon([(23, 44), (32, 44), (27, 51)], fill=(250, 248, 244, 255))
    elif outfit == 'tux':
        d.polygon([(23, 44), (32, 44), (29, 58), (26, 58)], fill=(250, 250, 252, 255)); d.rectangle([25, 45, 30, 47], fill=(190, 34, 54, 255))
    out.alpha_composite(outline(body, shade(td, .5)).crop((1, 1, W + 1, H + 1)))
    # cara grande + cuello corto
    face = np.zeros((H, W, 4), np.uint8)
    for y in range(HY + 28, HY + 39):
        for x in range(HX + 14, HX + 22): face[y, x] = (*sk['s'], 255)
    for y in range(HY + 28, HY + 33):
        for x in range(HX + 14, HX + 22): face[y, x] = (*sk['t'], 255)
    for r, (xl, xr) in CONTOUR.items():
        for c in range(xl, xr + 1):
            face[HY + r, HX + c] = (*sk['S'], 255)
            if c >= xr - 4 and 3 <= r <= 29: face[HY + r, HX + c] = (*sk['s'], 255)          # sombra del lado derecho
    if style != 'tab':
        for r in range(15, 22): face[HY + r, HX + 32] = (*sk['s'], 255)
        for r in range(16, 21): face[HY + r, HX + 33] = (*sk['s'], 255)
        face[HY + 18, HX + 32] = (*sk['t'], 255)
    for r in range(4, 12):                                              # luz en la frente y pómulo
        face[HY + r, HX + 8] = (*sk['L'], 255); face[HY + r, HX + 9] = (*sk['L'], 255)
    for r in range(20, 24): face[HY + r, HX + 8] = (*sk['L'], 255)
    if CS.get('stubble'):
        hb_ = np.array(hc['b'], float); stub = tuple(int(v) for v in np.array(CS['skin'], float) * .8 + hb_ * .2)
        for r in range(23, 32):                                   # barba de dos días: tono suave en mandíbula y barbilla
            xl, xr = CONTOUR[r]
            for c in range(xl, xr - 4):
                if r >= 26 or c <= xl + 2: face[HY + r, HX + c] = (*stub, 255)
    # rasgos
    closed = blink or expr == 'smile'
    sleepy = CS.get('sleepy') and not closed
    near = EYE_NEAR_CLOSED if closed else (EYE_NEAR_SLEEPY if sleepy else EYE_NEAR)
    farr = EYE_FAR_CLOSED if closed else (EYE_FAR_SLEEPY if sleepy else EYE_FAR)
    stamp(face, rows_at(13, 18, near) + rows_at(13, 7, farr), HX, HY, pal)
    if style == 'tab' and not closed:
        stamp(face, [(12, 27, 'K'), (13, 27, 'K'), (13, 6, 'K'), (12, 6, 'K')], HX, HY, pal)       # pestañas exteriores
    stamp(face, BROWS['sad' if expr in ('sad', 'worry') else 'n'], HX, HY, {'K': hc['dd']})
    stamp(face, NOSE, HX, HY, pal)
    stamp(face, MOUTHS.get(expr, MOUTHS['n']), HX, HY, pal)
    if style in ('tab', 'you'):
        stamp(face, [(21, 8, 'mmm'), (21, 24, 'mmm')], HX, HY, {'m': (240, 150, 150)})
    out.alpha_composite(layer(face, shade(CS['skin'], .45)))
    # pelo frontal ceñido a la cabeza
    hair = np.zeros((H, W, 4), np.uint8)
    for r, row in enumerate(HAIR[style].strip('\n').split('\n')):
        for c, ch in enumerate(row):
            if ch in 'AaBb':
                x, y = HX + c, HY + r - 4
                if 0 <= x < W and 0 <= y < H: hair[y, x] = (*pal[ch], 255)
    out.alpha_composite(layer(hair, shade(hc['dd'], .6)))
    return out


